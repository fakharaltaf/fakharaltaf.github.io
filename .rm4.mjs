import { chromium } from '@playwright/test'
const [, , out, w = '1280', h = '800', mode = ''] = process.argv
const b = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-unsafe-webgpu'] })
const pg = await b.newPage({ viewport: { width: +w, height: +h } })
const errs = []; pg.on('pageerror', (e) => errs.push(e.message)); pg.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
await pg.goto('http://localhost:5173/' + (mode ? '?' + mode : '') + '#raremind')
await pg.waitForFunction(() => document.documentElement.classList.contains('world-ready'))
await pg.waitForTimeout(3500)
await pg.screenshot({ path: `${out}/rm-${w}-a.png` })
await pg.fill('#raremind-answer', 'mango'); await pg.keyboard.press('Enter'); await pg.waitForTimeout(500)
await pg.fill('#raremind-answer', 'durian'); await pg.keyboard.press('Enter'); await pg.waitForTimeout(900)
await pg.fill('#raremind-answer', 'Jamun'); await pg.keyboard.press('Enter'); await pg.waitForTimeout(2500)
await pg.screenshot({ path: `${out}/rm-${w}-b.png` })
console.log('result:', await pg.locator('.rm-result').innerText(), '| depth:', await pg.locator('.rm-depth').innerText())
console.log('panel:', await pg.locator('.script-panel .file').innerText().catch(() => 'none'))
await pg.click('.demo-expand'); await pg.waitForTimeout(1200)
await pg.screenshot({ path: `${out}/rm-${w}-c.png` })
await pg.keyboard.press('Escape'); await pg.waitForTimeout(800)
console.log('expanded after esc:', await pg.evaluate(() => document.querySelector('.demo-host').classList.contains('expanded')))
console.log(errs.slice(0, 5).join('\n') || 'no errors')
await b.close()
