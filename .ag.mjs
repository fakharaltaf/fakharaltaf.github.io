import { chromium } from '@playwright/test'
const [, , out, w = '1280', h = '800'] = process.argv
const b = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-unsafe-webgpu'] })
const pg = await b.newPage({ viewport: { width: +w, height: +h } })
const errs = []; pg.on('pageerror', (e) => errs.push(e.message)); pg.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
await pg.goto('http://localhost:5173/#constellation')
await pg.waitForFunction(() => document.documentElement.classList.contains('world-ready'))
await pg.waitForTimeout(3500)
await pg.screenshot({ path: `${out}/ag-${w}-0.png` })
await pg.click('button[aria-label="Open Agrarian"]')
await pg.waitForTimeout(800)
await pg.screenshot({ path: `${out}/ag-${w}-mid.png` })
await pg.waitForTimeout(3500)
console.log('hash:', await pg.evaluate(() => location.hash))
await pg.screenshot({ path: `${out}/ag-${w}-a.png` })
const box = await pg.locator('.ag-plot').boundingBox()
await pg.mouse.click(box.x + box.width * 0.5, box.y + box.height * 0.55); await pg.waitForTimeout(400)
await pg.mouse.click(box.x + box.width * 0.55, box.y + box.height * 0.6); await pg.waitForTimeout(600)
await pg.click('.ag-bottom .btn'); await pg.waitForTimeout(7000)
await pg.screenshot({ path: `${out}/ag-${w}-b.png` })
console.log('hud:', await pg.locator('.ag-hud').innerText(), '|', await pg.locator('.ag-event').innerText())
console.log('panel:', await pg.locator('.script-panel .file').innerText().catch(() => 'none'))
await pg.keyboard.press('Escape'); await pg.waitForTimeout(3000)
console.log('after esc hash:', await pg.evaluate(() => location.hash))
console.log(errs.slice(0, 5).join('\n') || 'no errors')
await b.close()
